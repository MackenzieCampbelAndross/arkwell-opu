"""Hardware-aware Conflict Analyzer for OPU candidate updates."""

from dataclasses import dataclass, field
from enum import Enum, auto
import time
from typing import Dict, List, Set, Tuple
import numpy as np
from arkwell.simulator.compiler.mis_compiler import OPUCompiledProblem


class ConflictType(Enum):
    """Classification of conflict types across candidate updates."""
    NONE = auto()
    READ_WRITE = auto()
    OBJECTIVE_COUPLING = auto()
    CONSTRAINT_DEPENDENCY = auto()
    FEASIBILITY_VIOLATION = auto()
    NONCOMMUTING = auto()
    RESOURCE_COLLISION = auto()


@dataclass
class CandidateUpdate:
    """A proposed local search update generated by a Processing Element."""
    pe_id: int
    var_idx: int
    current_val: int
    proposed_val: int
    delta_objective: float


@dataclass
class ConflictGraphResult:
    """Result of conflict graph analysis."""
    candidates: List[CandidateUpdate]
    num_candidates: int
    conflict_matrix: np.ndarray  # Shape (K, K), bool
    conflict_types: Dict[Tuple[int, int], ConflictType]
    num_conflicts: int
    conflict_density: float
    analysis_time_seconds: float


class ConflictAnalyzer:
    """
    Evaluates mutual compatibility of candidate updates and constructs
    the hardware conflict graph G_conf = (V_cand, E_conf).
    """

    def __init__(self, compiled: OPUCompiledProblem):
        self.compiled = compiled
        self.n = compiled.num_variables
        self.m = compiled.num_constraints
        self.adj = compiled.adjacency_list
        self.edges_set: Set[Tuple[int, int]] = set()
        if self.m > 0:
            for u, v in compiled.constraint_graph.constraint_edges:
                self.edges_set.add((min(int(u), int(v)), max(int(u), int(v))))

    def analyze_candidates(
        self,
        candidates: List[CandidateUpdate],
        current_state: np.ndarray,
    ) -> ConflictGraphResult:
        """
        Builds the pairwise conflict graph over candidate updates.
        """
        start_time = time.perf_counter()
        k = len(candidates)
        if k == 0:
            return ConflictGraphResult(
                candidates=[],
                num_candidates=0,
                conflict_matrix=np.empty((0, 0), dtype=bool),
                conflict_types={},
                num_conflicts=0,
                conflict_density=0.0,
                analysis_time_seconds=0.0,
            )

        conflict_matrix = np.zeros((k, k), dtype=bool)
        conflict_types: Dict[Tuple[int, int], ConflictType] = {}

        for a in range(k):
            u_a = candidates[a]
            for b in range(a + 1, k):
                u_b = candidates[b]
                has_conflict = False
                c_type = ConflictType.NONE

                # 1. Resource collision: same PE proposing multiple distinct moves in single cycle
                if u_a.pe_id == u_b.pe_id:
                    has_conflict = True
                    c_type = ConflictType.RESOURCE_COLLISION

                # 2. Variable identity collision: duplicate update on same variable
                elif u_a.var_idx == u_b.var_idx:
                    has_conflict = True
                    c_type = ConflictType.READ_WRITE

                else:
                    # 3. Constraint & Feasibility check
                    # In MIS, both proposing 0 -> 1 conflicts iff edge (u_a, u_b) exists in G
                    edge_key = (min(u_a.var_idx, u_b.var_idx), max(u_a.var_idx, u_b.var_idx))
                    if edge_key in self.edges_set:
                        # Shared constraint exists!
                        if u_a.proposed_val == 1 and u_b.proposed_val == 1:
                            # Both adding to independent set -> mutual violation!
                            has_conflict = True
                            c_type = ConflictType.FEASIBILITY_VIOLATION
                        else:
                            # One or both are removals (1 -> 0) -> no feasibility violation
                            c_type = ConflictType.CONSTRAINT_DEPENDENCY

                    # 4. Objective coupling:
                    if not self.compiled.objective_graph.is_linear:
                        # (Checked if non-linear objective terms couple var_a and var_b)
                        pass

                if has_conflict:
                    conflict_matrix[a, b] = True
                    conflict_matrix[b, a] = True
                    conflict_types[(a, b)] = c_type
                    conflict_types[(b, a)] = c_type

        total_possible = k * (k - 1) // 2
        actual_conflicts = int(np.sum(conflict_matrix)) // 2
        density = (actual_conflicts / total_possible) if total_possible > 0 else 0.0
        elapsed = time.perf_counter() - start_time

        return ConflictGraphResult(
            candidates=candidates,
            num_candidates=k,
            conflict_matrix=conflict_matrix,
            conflict_types=conflict_types,
            num_conflicts=actual_conflicts,
            conflict_density=density,
            analysis_time_seconds=elapsed,
        )
